using System.Linq.Expressions;
using LvvErp.Application.Common.Interfaces;
using LvvErp.Application.Common.Persistence;
using LvvErp.Domain.Common;
using LvvErp.Domain.Features.Employees;
using LvvErp.Domain.Features.Identity;
using LvvErp.Domain.Features.Inventory;
using LvvErp.Domain.Features.Purchasing;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;

namespace LvvErp.Infrastructure.Persistence;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options), IAppDbContext
{
    /// <summary>ICU collation for columns users sort by name; apply with <c>.UseCollation(VietnameseCollation)</c>.</summary>
    public const string VietnameseCollation = "vi_vn";

    public DbSet<User> Users => Set<User>();

    public DbSet<Employee> Employees => Set<Employee>();
    public DbSet<Department> Departments => Set<Department>();
    public DbSet<Position> Positions => Set<Position>();

    public DbSet<Unit> Units => Set<Unit>();
    public DbSet<MaterialGroup> MaterialGroups => Set<MaterialGroup>();
    public DbSet<Warehouse> Warehouses => Set<Warehouse>();
    public DbSet<Location> Locations => Set<Location>();
    public DbSet<Material> Materials => Set<Material>();
    public DbSet<Lot> Lots => Set<Lot>();
    public DbSet<StockDocument> StockDocuments => Set<StockDocument>();
    public DbSet<StockDocumentLine> StockDocumentLines => Set<StockDocumentLine>();
    public DbSet<StockTransaction> StockTransactions => Set<StockTransaction>();
    public DbSet<StockBalance> StockBalances => Set<StockBalance>();
    public DbSet<DocumentSequence> DocumentSequences => Set<DocumentSequence>();

    public DbSet<Supplier> Suppliers => Set<Supplier>();
    public DbSet<PurchasingSettings> PurchasingSettings => Set<PurchasingSettings>();
    public DbSet<PurchaseRequest> PurchaseRequests => Set<PurchaseRequest>();
    public DbSet<PurchaseRequestLine> PurchaseRequestLines => Set<PurchaseRequestLine>();
    public DbSet<PurchaseOrder> PurchaseOrders => Set<PurchaseOrder>();
    public DbSet<PurchaseOrderLine> PurchaseOrderLines => Set<PurchaseOrderLine>();
    public DbSet<PurchaseOrderLineSource> PurchaseOrderLineSources => Set<PurchaseOrderLineSource>();

    public Task<IDbContextTransaction> BeginTransactionAsync(CancellationToken cancellationToken = default) =>
        Database.BeginTransactionAsync(cancellationToken);

    public IDbContextTransaction? CurrentTransaction => Database.CurrentTransaction;

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Accent-insensitive search for Vietnamese names ("nguyen" matches "Nguyễn").
        modelBuilder.HasPostgresExtension("unaccent");
        // Vietnamese alphabetical order for names (default en_US puts "Đ" and "Ê" after "Z").
        modelBuilder.HasCollation(VietnameseCollation, locale: "vi-VN", provider: "icu", deterministic: true);
        modelBuilder.HasDbFunction(typeof(AppDbFunctions).GetMethod(nameof(AppDbFunctions.Unaccent))!)
            .HasName("unaccent")
            .IsBuiltIn();

        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        ApplyClientGeneratedKeys(modelBuilder);
        ApplySoftDeleteFilters(modelBuilder);
    }

    /// <summary>
    /// Ids are UUIDv7 assigned in code (<see cref="Entity"/>). Telling EF they are never generated by the
    /// database makes it treat a new child found through a navigation (e.g. a document's new lines)
    /// as Added; otherwise a non-empty key makes EF assume the row exists and issue an UPDATE.
    /// </summary>
    private static void ApplyClientGeneratedKeys(ModelBuilder modelBuilder)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            if (typeof(Entity).IsAssignableFrom(entityType.ClrType) && entityType.BaseType is null)
                modelBuilder.Entity(entityType.ClrType).Property(nameof(Entity.Id)).ValueGeneratedNever();
        }
    }

    private static void ApplySoftDeleteFilters(ModelBuilder modelBuilder)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            if (!typeof(ISoftDeletable).IsAssignableFrom(entityType.ClrType) || entityType.BaseType is not null)
                continue;

            // e => !e.IsDeleted
            var parameter = Expression.Parameter(entityType.ClrType, "e");
            var body = Expression.Not(Expression.Property(parameter, nameof(ISoftDeletable.IsDeleted)));
            modelBuilder.Entity(entityType.ClrType).HasQueryFilter(Expression.Lambda(body, parameter));
        }
    }
}
